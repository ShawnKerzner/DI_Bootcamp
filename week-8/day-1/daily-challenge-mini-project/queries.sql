runs_conceded = """
SELECT Bowler, b.Match_id, SUM(RUNS_SCORED) AS Runs_Conceded
FROM Ball_by_Ball b
JOIN Batsman_Scored s
  ON b.Match_ID = s.Match_ID
AND b.Over_ID = s.Over_ID
